const statusOptions = (values, defaultLabel = "All") => {
  const options = values.map((value) => ({
    value,
    label: value === "all" ? defaultLabel : value.replace(/-/g, " ").replace(/\b\w/g, (char) => char.toUpperCase()),
  }));
  
  if (!values.includes("all") && defaultLabel !== false) {
    return [{ value: "all", label: defaultLabel }, ...options];
  }
  
  return options;
};

