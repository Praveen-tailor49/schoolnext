export const moduleKeys = Object.keys(moduleConfigs);

export const canAccessModule = (key, role) => {
  const config = getModuleConfig(key);
  return Boolean(config && role && config.roles.includes(role));
};

export const canPerformAction = (config, action, role) =>
  Boolean(role && (config.actions?.[action] || config.roles).includes(role));
